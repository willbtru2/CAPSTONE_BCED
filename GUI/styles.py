import tkinter as tk
from tkinter import ttk

def configure_styles(style):
        style = ttk.Style()
        style.theme_use("clam")
# Colors
        colors={
            "genbackground":"black",
            "conbackground":"lightsteelblue1",
            "msgbackground":"honeydew2",
            "opsbackground":"lavender",
            "outbackground":"slategrey",
            "conheading":"lightskyblue2",
            "msgheading":"darkseagreen",
            "opsheading":"plum1",
            "outheading":"steelblue4",
            "panel":"#F7FBFF",
            "genheading":"#1F4E79",
            "heading_text":"white",
            "new_text":"#17365D",
            "text":"white",
            "uploadbutton":"lightblue",
            "generatebutton":"green",
            "encodebutton":"#5B9BD5",
            "decodebutton":"mediumpurple",
            "schemebutton":"black",
            "button_text":"white",
            "success":"#70AD47",
            "operation":"#8064A2"
            }
# Frame Styles
        style.configure(
            "ConFrame.TFrame",
            background=colors["conbackground"],
            borderwidth=2,
            relief="raised")
        style.configure(
            "EncFrame.TFrame",
            background=colors["conbackground"])
        style.configure(
            "MsgFrame.TFrame",
            background=colors["msgbackground"],
            borderwidth=2,
            relief="raised")
        style.configure(
            "StsFrame.TFrame",
            background=colors["opsbackground"],
            borderwidth=2,
            relief="raised")
        style.configure(
            "OpsFrame.TFrame",
            background=colors["opsbackground"],
            borderwidth=2,
            relief="raised")
        style.configure(
            "OutFrame.TFrame",
            background=colors["outbackground"],
            borderwidth=2,
            relief="solid")
        style.configure(
            "FPGAFrame.TFrame",
            background="black",
            borderwidth=2,
            relief="solid")
        style.configure(
            "BtnFrame.TFrame",
            background=colors["msgbackground"])
        
# Heading Styles
        style.configure(
            "Heading.TLabel",
            font=("Arial",12,"bold"),
            foreground=colors["heading_text"],
            background=colors["genheading"],
            anchor="center")
        style.configure(
            "ConHeading.TLabel",
            font=("Arial",14,"bold"),
            foreground=colors["heading_text"],
            background=colors["conheading"],
            anchor="center")
        style.configure(
            "MsgHeading.TLabel",
            font=("Arial",14,"bold"),
            foreground=colors["heading_text"],
            background=colors["msgheading"],
            anchor="center")
        style.configure(
            "OpsHeading.TLabel",
            font=("Arial",14,"bold"),
            foreground=colors["heading_text"],
            background=colors["opsheading"],
            anchor="center")
        style.configure(
            "OutHeading.TLabel",
            font=("Arial",14,"bold"),
            foreground=colors["heading_text"],
            background=colors["outheading"],
            anchor="center")
        style.configure(
            "FPGAHeading.TLabel",
            font=("Consolas",14,"bold"),
            foreground="black",
            background="green",
            anchor="center")
# Label Styles
        style.configure(
            "ConLabel.TLabel",
            background=colors["conbackground"])
        style.configure(
            "SchLabel.TLabel",
            background=colors["conbackground"],
            font=("Arial",9,"bold"),
            anchor="center")
        style.configure(
            "MsgLabel.TLabel",
            background=colors["msgbackground"])
        style.configure(
            "StsLabel.TLabel",
            background=colors["opsbackground"],
            font=("Arial",9,"bold"))
        style.configure(
            "OpsLabel.TLabel",
            background=colors["opsbackground"])
        style.configure(
            "OutLabel.TLabel",
            background=colors["outbackground"],
            foreground=colors["button_text"])
        style.configure(
            "FPGALabel.TLabel",
            font=("default",9,"bold"),
            background="black",
            foreground="green")
# Button Styles
        style.configure("Custom.TButton",font=("Arial",12,"bold"),padding=8)
        style.configure(
            "EncodeButton.TButton",
            font=("Arial",12,"bold"),
            foreground=colors["button_text"],
            background=colors["encodebutton"])
        style.configure(
            "DecodeButton.TButton",
            font=("Arial",12,"bold"),
            foreground=colors["button_text"],
            background=colors["decodebutton"])
        style.configure(
            "UploadButton.TButton",
            font=("Arial",10,"bold"),
            foreground=colors["button_text"],
            background=colors["uploadbutton"])
        style.configure(
            "GenerateButton.TButton",
            font=("Arial",10,"bold"),
            foreground=colors["button_text"],
            background=colors["success"])
        style.configure(
            "SchemeButton.TButton",
            font=("Arial",10,"bold"),
            foreground=colors["success"],
            background=colors["schemebutton"],
            borderwidth=2,
            relief="raised")
# ComboBox Styles
        style.configure(
            "EncodeBox.TCombobox",
            fieldbackground=colors["text"],
            background="white",
            foreground="black",
            selectbackground="white",
            selectforeground="black") 
        style.map(
            "EncodeBox.TCombobox",
            fieldbackground=[("readonly","white")],
            foreground=[("readonly","black")],
            selectbackground=[("readonly","white")],
            selectforeground=[("readonly","black")])
# Entry Styles
        style.configure(
            "InputEntry.TEntry",
            background=colors["text"],
            foreground=colors["genbackground"])
# Scrollbar Styles
        style.configure(
            "CustomScroll.TScrollbar",
            background=[("active","white"),("pressed","black")],
            throughcolor="green",
            bordercolor="green",
            lightcolor="white",
            darkcolor="black",
            arrowcolor="white",
            arrowsize="10",
            gripcount="2",
            borderwidth="1")
        
        
        return style
